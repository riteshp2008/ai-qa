import "server-only";

import { z } from "zod";

import type { Pipeline } from "@/domain/pipelines/types";
import { createChatModel } from "@/server/agents/llm/model";

const prSchema = z.object({ title: z.string().max(90), body: z.string() });

function resultsTable(pipeline: Pipeline) {
  const rows = Object.entries(pipeline.results.suites ?? {}).map(
    ([suite, result]) => `| ${suite.toUpperCase()} | ${result?.status} | ${result?.passed ?? 0} | ${result?.failed ?? 0} | ${result?.files.length ?? 0} |`,
  );
  return ["| Suite | Status | Passed | Failed | Files |", "| --- | --- | --- | --- | --- |", ...rows].join("\n");
}

/** Deterministic PR body; the model only adds a short narrative on top. */
function fallbackBody(pipeline: Pipeline, files: string[]) {
  const bugs = Object.values(pipeline.results.suites ?? {}).flatMap((result) => result?.suspectedBugs ?? []);
  return [
    "## Summary",
    `Automated tests generated and verified by Sentinel agents for \`${pipeline.repositoryFullName}\`.`,
    "",
    "## Verification",
    resultsTable(pipeline),
    pipeline.results.container ? `\nContainer: ${pipeline.results.container.status}${pipeline.results.container.createdDockerfile ? " (Dockerfile created by Sentinel)" : ""}.` : "",
    bugs.length ? `\n## Suspected application bugs\n${bugs.map((bug) => `- ${bug}`).join("\n")}` : "",
    "\n## Files",
    files.map((file) => `- \`${file}\``).join("\n"),
    "\n---\nGenerated by Sentinel. Reviewed and approved by a human before this PR was opened.",
  ].filter(Boolean).join("\n");
}

export async function writePullRequest(pipeline: Pipeline, files: string[]): Promise<{ title: string; body: string }> {
  const body = fallbackBody(pipeline, files);
  const suites = pipeline.suites.map((suite) => suite.toUpperCase()).join(", ");
  const fallback = { title: `test: add ${suites} tests generated by Sentinel`, body };
  try {
    const model = createChatModel("fast").withStructuredOutput(prSchema, { name: "pull_request" });
    const draft = await model.invoke([
      ["system", "Write a concise conventional-commit style PR title (e.g. 'test: add Playwright e2e coverage for checkout') and a 2-4 sentence overview paragraph. Do not invent results; use only the data given."],
      ["human", `Results:\n${JSON.stringify(pipeline.results, null, 2)}\nFiles: ${files.join(", ")}`],
    ]);
    return { title: draft.title, body: `${draft.body.trim()}\n\n${body}` };
  } catch {
    return fallback;
  }
}
